CREATE TABLE original_text
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL
);

ALTER TABLE flashcard
    DROP COLUMN original_text,
    ADD COLUMN original_text_id BIGINT NOT NULL,
    ADD CONSTRAINT fk_flashcard_original_text FOREIGN KEY (original_text_id) REFERENCES original_text (id);

CREATE INDEX idx_flashcard_original_text_id ON flashcard (original_text_id);
