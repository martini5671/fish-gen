-- Balance of AI credits each user can spend on generation. No CHECK >= 0: the real cost is only known after the
-- Anthropic call returns, so a single request may push the balance slightly below zero.
ALTER TABLE users
    ADD ai_credits BIGINT NOT NULL DEFAULT 0;

-- One row per Anthropic call, with the token counts the API reported. Kept as raw tokens (not credits)
-- so usage can be re-priced later.
CREATE TABLE token_usage
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    model         VARCHAR(100) NOT NULL,
    input_tokens  INTEGER      NOT NULL,
    output_tokens INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6),
    CONSTRAINT FK_TOKEN_USAGE_ON_USER FOREIGN KEY (user_id) REFERENCES users (id)
);

-- Supports listing a user's usage newest first and summing it over a date range; also covers the foreign key.
CREATE INDEX idx_token_usage_user_id_created_at ON token_usage (user_id, created_at);
